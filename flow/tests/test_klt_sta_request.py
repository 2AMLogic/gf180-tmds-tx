#!/usr/bin/env python3
"""Guard: flow/klt_sta_tmds_encoder.py's request vs the committed graded envelope.

`flow/tmds_encoder/klt_sta.json` is append-only, hash-pinned signoff evidence
(signoff/manifest.json -> 5.digital) and is what `klt signoff` grades for T1
item 5 (digital). After #319 the request constants track the flow family
automatically, so a ratified spec change can silently move what
`build_request()` would ask for while the committed envelope stays as graded
under the old values. These tests make that drift loud (issue #324).

Stdlib only; runs with no PDK, no `klt` and no `openroad`. The test imports
`klt_sta_tmds_encoder` and calls `build_request()` only -- never `main()`,
never a subprocess -- and writes nothing.
"""

from __future__ import annotations

import json
import re
import sys
import unittest
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parents[2]
ENVELOPE_PATH = REPO_ROOT / "flow" / "tmds_encoder" / "klt_sta.json"
SPEC_PATH = REPO_ROOT / "spec" / "tmds-tx.md"

sys.path.insert(0, str(REPO_ROOT / "flow"))

import klt_sta_tmds_encoder as sta  # noqa: E402

# The pixel-clock period flow/tmds_encoder/klt_sta.json was graded under,
# emitted by the build recorded in its provenance.klt_version
# (klt 0.5.0+ge8ca621a6961). The envelope echoes no constraints block, so
# this constant is the only pin on the era it was graded in. Changing it --
# e.g. after a ratified pixel-clock change in spec/tmds-tx.md -- requires
# regenerating the envelope under the pinned grading build (signoff/README.md)
# and committing both together; the envelope is not regenerated by editing
# this constant. Issue #324.
GRADED_CLOCK_PERIOD_NS = 13.468


def spec_pixel_clock_mhz() -> float:
    """720p60 Target pixel clock from spec/tmds-tx.md section 1 (not section 2).

    The ratified target rows live in the section 1 table; the repo-wide
    "section 2" citation is a known mis-citation, out of scope here (see
    signoff/README.md, which also cites section 1).
    """
    for raw in SPEC_PATH.read_text().splitlines():
        line = raw.strip()
        if line.startswith("| Pixel clock |"):
            # | Pixel clock | 74.25 MHz | 27.000 MHz (nominal) | 148.5 MHz |
            # Index 2 is the Target column; the Fallback (480p, 27.000 MHz)
            # and Stretch (1080p60, 148.5 MHz) columns share the row.
            target = line.split("|")[2].strip()
            m = re.fullmatch(r"(\d+(?:\.\d+)?)\s*MHz", target)
            if not m:
                raise AssertionError(
                    f"unparsable Target column in spec/tmds-tx.md pixel-clock row: {target!r}"
                )
            return float(m.group(1))
    raise AssertionError("no '| Pixel clock |' row found in spec/tmds-tx.md target table")


class KltStaRequestGuard(unittest.TestCase):
    """The request build_request() would send today still describes the envelope."""

    @classmethod
    def setUpClass(cls):
        cls.request = sta.build_request()
        cls.envelope = json.loads(ENVELOPE_PATH.read_text())

    def test_corners_match_envelope_same_order(self):
        envelope_corners = [c["corner"] for c in self.envelope["corners"]]
        self.assertEqual(
            self.request["pdk"]["corners"],
            envelope_corners,
            "build_request() corners no longer match the committed graded "
            f"envelope {ENVELOPE_PATH} (order included). The envelope is "
            "append-only signoff evidence: regenerate it under the pinned "
            "grading build before changing the request, and commit both "
            "together.",
        )

    def test_cell_library_matches_envelope(self):
        libraries = set()
        for c in self.envelope["corners"]:
            name = c["deck"]["name"]
            suffix = f"__{c['corner']}"
            self.assertTrue(
                name.endswith(suffix),
                f"envelope deck name {name!r} does not end in {suffix!r}; "
                "cannot recover the cell library from the committed envelope",
            )
            libraries.add(name[: -len(suffix)])
        self.assertEqual(
            len(libraries),
            1,
            f"committed graded envelope {ENVELOPE_PATH} records conflicting "
            f"cell libraries across corners: {sorted(libraries)}",
        )
        self.assertEqual(
            self.request["pdk"]["cell_library"],
            libraries.pop(),
            "build_request() cell library no longer matches the committed "
            f"graded envelope {ENVELOPE_PATH}. The envelope is append-only "
            "signoff evidence: regenerate it under the pinned grading build "
            "before changing the library, and commit both together.",
        )

    def test_clock_period_matches_ratified_spec(self):
        f_mhz = spec_pixel_clock_mhz()
        expected = round(1000.0 / f_mhz, 4)
        self.assertAlmostEqual(
            self.request["constraints"]["clock_period_ns"],
            expected,
            msg="build_request() clock period no longer matches the 720p60 "
            f"pixel clock ({f_mhz} MHz) ratified in spec/tmds-tx.md section 1. "
            "A ratified clock change must move spec, synth.TARGET_FREQ_MHZ "
            "and the request together -- and requires regenerating "
            "flow/tmds_encoder/klt_sta.json under the pinned grading build.",
        )

    def test_clock_period_matches_graded_envelope_era(self):
        self.assertAlmostEqual(
            self.request["constraints"]["clock_period_ns"],
            GRADED_CLOCK_PERIOD_NS,
            msg="build_request() clock period no longer equals the period "
            f"flow/tmds_encoder/klt_sta.json was graded under "
            f"({GRADED_CLOCK_PERIOD_NS} ns, klt 0.5.0+ge8ca621a6961). The "
            "envelope is append-only signoff evidence: regenerate it under "
            "the pinned grading build before changing the period, and commit "
            "both together.",
        )


if __name__ == "__main__":
    unittest.main()
