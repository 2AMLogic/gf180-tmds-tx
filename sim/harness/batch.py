"""Batch backend: run a PVT grid through ``klt sim --backend batch``.

Dispatch workers must not hand-launch ``ngspice -b`` grids (see the host
rules), so the local ``runner.run_grid`` cannot produce a recorded PVT result
there. This module is the boundary that turns each ``PvtPoint`` into a
``klt sim`` request, submits it to the Spot batch fleet, and maps the returned
report back into the existing ``PointResult`` shape so ``report.py`` (and
``check_records.py``) work unchanged. It follows the sibling sky130-bandgap
``sim/bin/batch_sim.py`` boundary: one request per point, submit, collect,
assemble -- and **no local fallback**, ever.

Request construction reuses the same pieces ``runner.compose_deck`` uses (the
``.param`` block, the PDK design include, tolerances, the DUT and testbench
includes, the ``measure`` entries) -- literally the same code, via ``runner``'s
shared assembly helpers, so the two backends cannot drift into describing
different circuits (issue #308). ``klt sim`` wants a circuit *body*, so the
pieces that ``compose_deck`` puts in a full deck go into a generated body file
and the model library / process sections / temperature / analysis go into the
request fields.

Loud failure: every problem (klt missing, submit refused, unparseable report,
a point with no corner, several corners for one point, a missing measurement)
becomes a non-``ok`` ``PointResult``; ``assemble`` additionally refuses a
result list that does not cover the grid exactly once. A record built from
such results has status ``error`` -- never ``pass``.
"""

from __future__ import annotations

import json
import os
import re
import subprocess
from concurrent.futures import ThreadPoolExecutor
from pathlib import Path

from .corners import PvtPoint
from .pdk import Pdk
from .runner import (
    DEFAULT_TIMEOUT_S,
    PointResult,
    _dut_lines,
    _is_raw_meas_expr,
    _option_lines,
    _param_lines,
    _pdk_include_lines,
    _rate_note,
    _testbench_include_lines,
)
from .testbench import Testbench

KLT = os.environ.get("KLT_BIN", "klt")
#: Seconds `klt sim` waits for fleet capacity per submit (host rule: every
#: batch `klt sim` passes --wait-for-capacity 600).
CAPACITY_WAIT_S = 600
#: Submits are cheap (they wait on the fleet, they do not simulate here); keep
#: the in-flight count modest anyway so a burst does not trip the vCPU budget.
MAX_IN_FLIGHT = 2

_NAME_RE = re.compile(r"^[A-Za-z_][A-Za-z0-9_]*$")


class BatchError(RuntimeError):
    """The grid cannot be expressed or assembled as a batch run."""


def _analysis(tb: Testbench) -> tuple[str, str]:
    if len(tb.analyses) != 1:
        raise BatchError(
            f"{tb.name}: the batch backend supports exactly one analysis per "
            f"request (klt sim contract); this testbench declares {len(tb.analyses)}"
        )
    parts = tb.analyses[0].split(None, 1)
    return parts[0].lower(), parts[1] if len(parts) > 1 else ""


def _measurements(tb: Testbench, kind: str) -> list[dict]:
    out = []
    for name, expr in tb.measure.items():
        if not _NAME_RE.match(name):
            raise BatchError(f"measurement name {name!r} is not a valid klt sim name")
        if "\n" in expr:
            raise BatchError(f"measurement {name!r}: expression must be one line")
        if _is_raw_meas_expr(expr):
            out.append({"name": name, "spice": f".meas {kind} {name} {expr}"})
        else:
            out.append({"name": name, "expr": expr})
    return out


def compose_body(tb: Testbench, pdk: Pdk, point: PvtPoint) -> str:
    """Circuit body for one point: the pieces of ``compose_deck`` that are not
    request fields (no ``.lib``, ``.temp``, ``.control`` or ``.end``).

    Every shared directive comes from ``runner``'s assembly helpers, so this
    body and the local backend's full deck cannot drift into describing
    different circuits (issue #308). What stays here is only what is specific
    to the batch body: its own header comment, and the absence of the deck
    banners and blank lines a request body has no use for.
    """
    lines = [
        f"* {tb.name} @ {point.corner_id} -- GENERATED by sim/harness (batch), do not edit",
        f"* temp={point.temp_c} C  vdd={point.vdd} V  rate={_rate_note(point)}  pdk={pdk.variant}@{pdk.version}",
    ]
    lines += _param_lines(tb, point)
    lines += _pdk_include_lines(pdk)
    lines += _option_lines(tb)
    lines += _dut_lines(tb)
    lines += _testbench_include_lines(tb)
    return "\n".join(lines) + "\n"


def build_request(
    tb: Testbench,
    pdk: Pdk,
    point: PvtPoint,
    netlist_name: str,
    timeout_s: int = DEFAULT_TIMEOUT_S,
) -> dict:
    """The ``klt sim`` request document for one PVT point."""
    kind, args = _analysis(tb)
    model_lib = Path(pdk.model_lib)
    try:
        lib_rel = str(model_lib.relative_to(pdk.path))
    except ValueError:
        lib_rel = str(model_lib)
    return {
        "netlist": netlist_name,
        "engine": "ngspice",
        "backend": "batch",
        "models": {"pdk": pdk.variant, "lib": lib_rel},
        "corners": {
            "process": [
                {"name": point.corner.name, "sections": list(point.corner.sections)}
            ],
            "temperature_c": [point.temp_c],
        },
        "analysis": {"kind": kind, "args": args},
        "measurements": _measurements(tb, kind),
        "options": {"timeout_s": timeout_s, "keep_artifacts": True},
        "batch": {"capacity_wait_s": CAPACITY_WAIT_S},
    }


def write_point_files(
    tb: Testbench, pdk: Pdk, point: PvtPoint, workdir: Path, timeout_s: int = DEFAULT_TIMEOUT_S
) -> Path:
    """Write the body and request for ``point`` under ``workdir``; return the request path."""
    workdir.mkdir(parents=True, exist_ok=True)
    body_name = f"{point.corner_id}.body.spice"
    (workdir / body_name).write_text(compose_body(tb, pdk, point))
    request = build_request(tb, pdk, point, body_name, timeout_s=timeout_s)
    path = workdir / f"{point.corner_id}.request.json"
    path.write_text(json.dumps(request, indent=2) + "\n")
    return path


def dry_run_text(
    tb: Testbench, pdk: Pdk, points: list[PvtPoint], timeout_s: int = DEFAULT_TIMEOUT_S
) -> str:
    """Printable requests for every point; submits nothing."""
    chunks = []
    for point in points:
        request = build_request(tb, pdk, point, f"{point.corner_id}.body.spice", timeout_s)
        chunks.append(f"# point {point.corner_id}\n" + json.dumps(request, indent=2))
    return "\n".join(chunks) + "\n"


def _failed(point: PvtPoint, status: str, message: str, seconds: float = 0.0, log: str = "") -> PointResult:
    return PointResult(
        point=point, status=status, seconds=seconds, log=log, message=message, backend="batch"
    )


def _parse_report(point: PvtPoint, tb: Testbench, report: dict, log_name: str) -> PointResult:
    corners = report.get("corners")
    if not isinstance(corners, list):
        return _failed(point, "error", "klt sim report has no corners list")
    if len(corners) != 1:
        kind = "missing" if not corners else "duplicate"
        return _failed(
            point, "error", f"{kind} point: expected exactly 1 corner, report has {len(corners)}"
        )
    corner = corners[0]
    remote = (report.get("environment") or {}).get("remote") or {}
    job_id = str(remote.get("job_id") or "")
    engine = str((report.get("environment") or {}).get("engine_version") or "")
    values: dict[str, float] = {}
    for m in corner.get("measurements") or []:
        value = m.get("value")
        if isinstance(value, (int, float)) and not isinstance(value, bool):
            values[m.get("name")] = float(value)
    missing = [name for name in tb.measure if name not in values]
    seconds = float(corner.get("runtime_s") or 0.0)
    status = "ok"
    message = ""
    if corner.get("status") in ("error", "inconclusive") or report.get("status") == "error":
        status = "error"
    if missing:
        status = "failed" if status == "ok" else status
    if status != "ok":
        diags = "; ".join(
            str(d.get("message") or d.get("code")) for d in (corner.get("diagnostics") or [])[:3]
        )
        message = diags or f"klt sim corner status {corner.get('status')!r}"
    if job_id == "":
        status, message = "error", (message + "; " if message else "") + "report names no batch job_id"
    result = PointResult(
        point=point,
        status=status,
        measurements=values,
        missing=missing,
        seconds=seconds,
        log=log_name,
        message=message,
        backend="batch",
        job_id=job_id,
        engine_version=engine,
    )
    return result


def run_point(
    tb: Testbench,
    pdk: Pdk,
    point: PvtPoint,
    workdir: Path,
    timeout_s: int = DEFAULT_TIMEOUT_S,
    log_dir: Path | None = None,
    klt: str | None = None,
) -> PointResult:
    """Submit one point to the batch fleet. Never raises for a sim failure and
    never runs ngspice locally."""
    klt = klt or KLT
    log_dir = workdir if log_dir is None else log_dir
    log_dir.mkdir(parents=True, exist_ok=True)
    request_path = write_point_files(tb, pdk, point, workdir, timeout_s)
    out_dir = workdir / f"{point.corner_id}.out"
    log_name = f"{point.corner_id}.log"
    cmd = [
        klt, "sim", str(request_path),
        "--backend", "batch",
        "--wait-for-capacity", str(CAPACITY_WAIT_S),
        "--format", "json",
        "-o", str(out_dir),
    ]
    try:
        proc = subprocess.run(cmd, capture_output=True, text=True, check=False)
    except FileNotFoundError:
        return _failed(point, "error", f"{klt!r} not found on PATH; batch backend needs klt (no local fallback)")
    (log_dir / log_name).write_text(
        f"$ {' '.join(cmd)}\nexit={proc.returncode}\n--- stdout ---\n{proc.stdout}\n--- stderr ---\n{proc.stderr}\n"
    )
    try:
        report = json.loads(proc.stdout)
    except ValueError:
        err = (proc.stderr.strip().splitlines() or ["no output"])[-1]
        return _failed(
            point, "error", f"klt sim exit {proc.returncode}, no JSON report: {err}", log=log_name
        )
    result = _parse_report(point, tb, report, log_name)
    if proc.returncode != 0 and result.status == "ok":
        result.status = "error"
        result.message = f"klt sim exit {proc.returncode} despite a complete report"
    return result


def assemble(points: list[PvtPoint], results: list[PointResult]) -> list[PointResult]:
    """Check ``results`` covers ``points`` exactly once, in grid order.

    Raises ``BatchError`` on a missing, duplicate or unexpected point -- a
    grid that is not fully accounted for must never become a record.
    """
    expected = [p.corner_id for p in points]
    got = [r.point.corner_id for r in results]
    problems = []
    for cid in expected:
        n = got.count(cid)
        if n == 0:
            problems.append(f"missing point {cid}")
        elif n > 1:
            problems.append(f"duplicate point {cid} (x{n})")
    problems += [f"unexpected point {cid}" for cid in got if cid not in expected]
    if problems:
        raise BatchError("batch grid not fully accounted for: " + "; ".join(problems))
    by_id = {r.point.corner_id: r for r in results}
    return [by_id[cid] for cid in expected]


def run_grid(
    tb: Testbench,
    pdk: Pdk,
    points: list[PvtPoint],
    workdir: Path,
    jobs: int = MAX_IN_FLIGHT,
    timeout_s: int = DEFAULT_TIMEOUT_S,
    on_result=None,
    log_dir: Path | None = None,
    klt: str | None = None,
) -> list[PointResult]:
    """Submit every point; results come back in grid order."""
    _analysis(tb)  # refuse an inexpressible bench before submitting anything
    _measurements(tb, _analysis(tb)[0])
    jobs = max(1, min(jobs, MAX_IN_FLIGHT))

    def _one(point):
        result = run_point(tb, pdk, point, workdir, timeout_s, log_dir, klt)
        if on_result is not None:
            on_result(result)
        return result

    if jobs == 1:
        results = [_one(p) for p in points]
    else:
        with ThreadPoolExecutor(max_workers=jobs) as pool:
            results = list(pool.map(_one, points))
    return assemble(points, results)


def engine_summary(results: list[PointResult]) -> str:
    """The ngspice version(s) the batch runner reported, for the record."""
    versions = sorted({r.engine_version for r in results if r.engine_version})
    return ", ".join(f"ngspice-{v}" if v.isdigit() else v for v in versions) or "unreported (batch)"
